export const allPages = [overviewPage, ...navigation.flatMap((group) => group.pages)];

export const findPageByPath = (pathname: string) =>
  allPages.find((page) => page.path === pathname);

export const findGroupByPage = (page?: NavPage) =>
  navigation.find((group) => group.pages.some((item) => item.code === page?.code));
