import type { NavGroup, NavPage, PageKind } from "../types";

type SourcePage = [code: string, title: string, description: string];

const createGroup = (
  key: string,
  title: string,
  kind: PageKind,
  source: SourcePage[],
): NavGroup => ({
  key,
  title,
  pages: source.map(([code, pageTitle, description]) => ({
    code,
    title: pageTitle,
    description,
    kind,
    path: `/app/${key}/${code.toLowerCase()}`,
    badge:
      pageTitle === "实时告警"
        ? 7
        : pageTitle === "指令中心"
          ? 3
          : pageTitle === "数据质量总览"
            ? 12
            : undefined,
  })),
});

